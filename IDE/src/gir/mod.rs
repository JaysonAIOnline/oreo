//! Graph Intermediate Representation (GIR) - Core Data Structures
//!
//! The GIR is the heart of OREO - a graph-native representation where code IS a graph,
//! not text that gets parsed into a graph. Every program is a directed acyclic graph
//! of nodes connected by typed edges.

