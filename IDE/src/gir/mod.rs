/// An edge connecting two ports
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GirEdge {
    pub id: EdgeId,
    pub source: PortId,
    pub target: PortId,
    pub edge_type: EdgeType,
    pub metadata: NodeMetadata,
}

/// Type of edge in the graph
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum EdgeType {
    Data,
    Control,
    Dependency,
    Composition,
    Annotation,
}

/// Registry for all types in the program
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TypeRegistry {
    pub types: HashMap<TypeId, TypeInfo>,
    pub name_to_id: HashMap<String, TypeId>,
}

impl TypeRegistry {
    pub fn new() -> Self {
        TypeRegistry {
            types: HashMap::new(),
            name_to_id: HashMap::new(),
        }
    }

    pub fn register(&mut self, name: String, info: TypeInfo) -> TypeId {
        let id = TypeId(self.types.len() as u64 + 1);
        self.name_to_id.insert(name.clone(), id);
        self.types.insert(id, info);
        id
    }

    pub fn get(&self, id: TypeId) -> Option<&TypeInfo> {
        self.types.get(&id)
    }

    pub fn get_by_name(&self, name: &str) -> Option<&TypeInfo> {
        self.name_to_id.get(name).and_then(|id| self.types.get(id))
    }
}

impl Default for TypeRegistry {
    fn default() -> Self {
        Self::new()
    }
}

/// Information about a type
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TypeInfo {
    pub id: TypeId,
    pub name: String,
    pub kind: TypeKind,
    pub parameters: Vec<TypeId>,
    pub constraints: Vec<TraitConstraint>,
    pub effects: EffectSet,
}

/// Kind of type
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum TypeKind {
    Primitive(PrimitiveType),
    Tuple(Vec<TypeId>),
    Record(Vec<(String, TypeId)>),
    Sum(Vec<(String, TypeId)>), // ADT variants
    Array(TypeId, Option<u64>), // element type, optional size
    Map(TypeId, TypeId),        // key, value
    Option(TypeId),
    Result(TypeId, TypeId),     // Ok, Err
    Function(FunctionType),
    Generic(TypeId),            // Type variable
    Effect(EffectId),
    Unknown,
}

/// Primitive types
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum PrimitiveType {
    Int(u8),      // Int(8), Int(16), Int(32), Int(64), Int(128)
    UInt(u8),     // UInt(8), UInt(16), UInt(32), UInt(64), UInt(128)
    Float(u8),    // Float(16), Float(32), Float(64), Float(80)
    Bool,
    Char,
    String,
    Bytes,
}

/// Function type with parameters, return, and effects
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FunctionType {
    pub params: Vec<(String, TypeId)>, // name, type
    pub return_type: TypeId,
    pub effects: EffectSet,
    pub is_async: bool,
    pub is_const: bool,
}

/// Effect set - a set of effects
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct EffectSet {
    pub effects: HashSet<EffectId>,
}

impl EffectSet {
    pub fn new() -> Self {
        EffectSet { effects: HashSet::new() }
    }

    pub fn add(&mut self, effect: EffectId) {
        self.effects.insert(effect);
    }

    pub fn remove(&mut self, effect: EffectId) {
        self.effects.remove(&effect);
    }

    pub fn contains(&self, effect: EffectId) -> bool {
        self.effects.contains(&effect)
    }

    pub fn union(&self, other: &EffectSet) -> EffectSet {
        let mut result = self.clone();
        result.effects.extend(other.effects.iter().copied());
        result
    }

    pub fn intersects(&self, other: &EffectSet) -> bool {
        self.effects.intersection(&other.effects).next().is_some()
    }

    pub fn is_subset_of(&self, other: &EffectSet) -> bool {
        self.effects.is_subset(&other.effects)
    }

    pub fn is_pure(&self) -> bool {
        self.effects.is_empty()
    }
}

