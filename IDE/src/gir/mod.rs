#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_gir_context_creation() {
        let mut ctx = GirContext::new();
        let graph_id = ctx.create_graph("main".to_string());
        assert_eq!(graph_id, GraphId(1));
        
        let graph = ctx.get_graph(graph_id).unwrap();
        assert_eq!(graph.name, "main");
    }

    #[test]
    fn test_effect_set_operations() {
        let mut set1 = EffectSet::new();
        let mut set2 = EffectSet::new();
        
        let e1 = EffectId(1);
        let e2 = EffectId(2);
        
        set1.add(e1);
        set2.add(e2);
        
        assert!(set1.contains(e1));
        assert!(!set1.contains(e2));
        
        let union = set1.union(&set2);
        assert!(union.contains(e1));
        assert!(union.contains(e2));
        
        assert!(set1.is_subset_of(&union));
        assert!(!set2.is_subset_of(&set1));
    }

    #[test]
    fn test_type_registry() {
        let mut registry = TypeRegistry::new();
        let type_id = registry.register(
            "Int32".to_string(),
            TypeInfo {
                id: TypeId(1),
                name: "Int32".to_string(),
                kind: TypeKind::Primitive(PrimitiveType::Int(32)),
                parameters: vec![],
                constraints: vec![],
                effects: EffectSet::new(),
            }
        );
        
        assert_eq!(type_id, TypeId(1));
        assert!(registry.get_by_name("Int32").is_some());
    }
}