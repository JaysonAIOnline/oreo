/// Unique identifier for a graph node
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct NodeId(pub u64);

/// Unique identifier for a graph edge
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct EdgeId(pub u64);

/// Unique identifier for a type
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct TypeId(pub u64);

/// Unique identifier for an effect
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct EffectId(pub u64);

/// Port identifier on a node
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct PortId {
    pub node_id: NodeId,
    pub index: u32,
    pub direction: PortDirection,
}

/// Direction of a port (input or output)
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum PortDirection {
    Input,
    Output,
}

/// Source location for debugging and error reporting
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SourceLocation {
    pub file: Option<String>,
    pub line: Option<u32>,
    pub column: Option<u32>,
    pub span: Option<(u32, u32)>, // (start, end) byte offsets
}

impl SourceLocation {
    pub fn unknown() -> Self {
        SourceLocation {
            file: None,
            line: None,
            column: None,
            span: None,
        }
    }
}

impl fmt::Display for SourceLocation {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if let Some(file) = &self.file {
            write!(f, "{}", file)?;
            if let Some(line) = self.line {
                write!(f, ":{}", line)?;
                if let Some(col) = self.column {
                    write!(f, ":{}", col)?;
                }
            }
        } else {
            write!(f, "<unknown>")?;
        }
        Ok(())
    }
}

/// Metadata attached to nodes and edges
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct NodeMetadata {
    /// Natural language description that produced this node
    pub nl_description: Option<String>,
    /// Source location in original NL or text
    pub source_location: Option<SourceLocation>,
    /// User-defined annotations
    pub annotations: HashMap<String, serde_json::Value>,
    /// Whether this node was generated by AI
    pub ai_generated: bool,
    /// Confidence score for AI-generated nodes (0.0 - 1.0)
    pub confidence: Option<f32>,
    /// Version/timestamp for incremental compilation
    pub version: u64,
}

/// Global GIR context containing all graphs and type/effect registries
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GirContext {
    /// All graphs in the program (modules, functions, etc.)
    pub graphs: HashMap<GraphId, GirGraph>,
    /// Type registry
    pub type_registry: TypeRegistry,
    /// Effect registry
    pub effect_registry: EffectRegistry,
    /// Next available IDs
    next_node_id: u64,
    next_edge_id: u64,
    next_type_id: u64,
    next_effect_id: u64,
    next_graph_id: u64,
}

/// Unique identifier for a graph
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct GraphId(pub u64);

impl GirContext {
    pub fn new() -> Self {
        GirContext {
            graphs: HashMap::new(),
            type_registry: TypeRegistry::new(),
            effect_registry: EffectRegistry::new(),
            next_node_id: 1,
            next_edge_id: 1,
            next_type_id: 1,
            next_effect_id: 1,
            next_graph_id: 1,
        }
    }

    pub fn create_graph(&mut self, name: String) -> GraphId {
        let id = GraphId(self.next_graph_id);
        self.next_graph_id += 1;
        let graph = GirGraph::new(id, name);
        self.graphs.insert(id, graph);
        id
    }

    pub fn get_graph(&self, id: GraphId) -> Option<&GirGraph> {
        self.graphs.get(&id)
    }

    pub fn get_graph_mut(&mut self, id: GraphId) -> Option<&mut GirGraph> {
        self.graphs.get_mut(&id)
    }

    pub fn next_node_id(&mut self) -> NodeId {
        let id = NodeId(self.next_node_id);
        self.next_node_id += 1;
        id
    }

    pub fn next_edge_id(&mut self) -> EdgeId {
        let id = EdgeId(self.next_edge_id);
        self.next_edge_id += 1;
        id
    }

    pub fn next_type_id(&mut self) -> TypeId {
        let id = TypeId(self.next_type_id);
        self.next_type_id += 1;
        id
    }

    pub fn next_effect_id(&mut self) -> EffectId {
        let id = EffectId(self.next_effect_id);
        self.next_effect_id += 1;
        id
    }
}

impl Default for GirContext {
    fn default() -> Self {
        Self::new()
    }
}

/// A single graph in the GIR (module, function, scope, etc.)
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GirGraph {
    pub id: GraphId,
    pub name: String,
    /// Nodes in this graph
    pub nodes: HashMap<NodeId, Box<dyn GirNode>>,
    /// Edges connecting nodes
    pub edges: HashMap<EdgeId, GirEdge>,
    /// Adjacency for fast traversal
    pub adjacency: HashMap<NodeId, Vec<EdgeId>>,
    /// Reverse adjacency
    pub reverse_adjacency: HashMap<NodeId, Vec<EdgeId>>,
    /// Entry points (e.g., main function, module exports)
    pub entry_points: Vec<NodeId>,
    /// Graph-level metadata
    pub metadata: NodeMetadata,
}

/// Trait for all node types in the GIR
pub trait GirNode: fmt::Debug + Send + Sync {
    fn id(&self) -> NodeId;
    fn node_type(&self) -> NodeType;
    fn input_ports(&self) -> &[Port];
    fn output_ports(&self) -> &[Port];
    fn metadata(&self) -> &NodeMetadata;
    fn metadata_mut(&mut self) -> &mut NodeMetadata;
    fn clone_box(&self) -> Box<dyn GirNode>;
    fn as_any(&self) -> &dyn std::any::Any;
    fn as_any_mut(&mut self) -> &mut dyn std::any::Any;
}

/// Discriminant for node type
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum NodeType {
    Value,
    Op,
    Control,
    Type,
    Effect,
    Meta,
}

/// A port on a node (input or output)
#[derive(Debug, Clone, Serialize, Deserialize)]
